// Generates src/brasil/data.ts from IBGE's public APIs: the 27 states and, for each state but the Distrito Federal,
// its 3 most populous cities after the capital (Censo 2022). Run: node scripts/generate-brasil-data.mjs
import { writeFileSync } from 'node:fs';

const API = 'https://servicodados.ibge.gov.br/api';
const OUT = new URL('../src/brasil/data.ts', import.meta.url);

// The capital's name is not in IBGE's state list. `extra` holds spellings people actually type.
const CAPITALS = {
  AC: { name: 'Rio Branco' },
  AL: { name: 'Maceió' },
  AP: { name: 'Macapá' },
  AM: { name: 'Manaus' },
  BA: { name: 'Salvador' },
  CE: { name: 'Fortaleza' },
  DF: { name: 'Brasília' },
  ES: { name: 'Vitória' },
  GO: { name: 'Goiânia' },
  MA: { name: 'São Luís', extra: ['São Luiz'] },
  MT: { name: 'Cuiabá' },
  MS: { name: 'Campo Grande' },
  MG: { name: 'Belo Horizonte' },
  PA: { name: 'Belém' },
  PB: { name: 'João Pessoa' },
  PR: { name: 'Curitiba' },
  PE: { name: 'Recife' },
  PI: { name: 'Teresina' },
  RJ: { name: 'Rio de Janeiro' },
  RN: { name: 'Natal' },
  RS: { name: 'Porto Alegre' },
  RO: { name: 'Porto Velho' },
  RR: { name: 'Boa Vista' },
  SC: { name: 'Florianópolis' },
  SP: { name: 'São Paulo' },
  SE: { name: 'Aracaju' },
  TO: { name: 'Palmas' },
};
const CITIES_PER_STATE = 3;

async function get(path) {
  const response = await fetch(`${API}${path}`);
  if (!response.ok) throw new Error(`${path}: ${response.status}`);
  return response.json();
}

const states = await get('/v1/localidades/estados?orderBy=nome');
// Table 4714, variable 93: resident population of every municipality in the 2022 census.
const [population] = await get('/v3/agregados/4714/periodos/2022/variaveis/93?localidades=N6[all]');
const municipalities = population.resultados[0].series.map(({ localidade, serie }) => {
  const [, name, abbr] = /^(.*) - ([A-Z]{2})$/.exec(localidade.nome);
  return { id: Number(localidade.id), name, abbr, population: Number(serie['2022']) };
});

const stateRows = states.map(({ id, sigla, nome }) => {
  const capital = CAPITALS[sigla];
  if (!capital) throw new Error(`No capital configured for ${sigla}`);
  return { code: id, abbr: sigla, name: nome, capital: capital.name, capitalExtra: capital.extra ?? [] };
});

const cityRows = stateRows
  .filter((state) => state.abbr !== 'DF')
  .flatMap((state) => {
    const inState = municipalities.filter((city) => city.abbr === state.abbr);
    if (!inState.some((city) => city.name === state.capital)) throw new Error(`Capital ${state.capital} not found`);
    return inState
      .filter((city) => city.name !== state.capital)
      .sort((a, b) => b.population - a.population)
      .slice(0, CITIES_PER_STATE)
      .map((city) => ({ id: city.id, name: city.name, stateCode: state.code, population: city.population }));
  });

const q = JSON.stringify;
let out = `// Generated by scripts/generate-brasil-data.mjs from IBGE (states API and Censo 2022). Do not edit by hand.
import type { BrasilCity, BrasilState } from './types';

export const BRASIL_STATES: readonly BrasilState[] = [
`;
for (const s of stateRows) {
  out += `  { code: ${s.code}, abbr: ${q(s.abbr)}, name: ${q(s.name)}, capital: ${q(s.capital)}, capitalAliases: ${q(s.capitalExtra)} },\n`;
}
out += `];\n\n/** For each state but the Distrito Federal, its ${CITIES_PER_STATE} most populous cities after the capital. */\nexport const BRASIL_CITIES: readonly BrasilCity[] = [\n`;
for (const c of cityRows) {
  out += `  { id: ${c.id}, name: ${q(c.name)}, stateCode: ${c.stateCode}, population: ${c.population} },\n`;
}
out += `];\n`;
writeFileSync(OUT, out);
console.log(`${stateRows.length} states, ${cityRows.length} cities -> ${OUT.pathname}`);
